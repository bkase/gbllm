//! End-to-end compiler-dataflow smoke (bd-1skgm): a checkpoint export
//! written to disk, compiled through the full `gbf_codegen::compile`
//! pipeline (import -> lower_infer -> lower_quant -> legalize ->
//! kernel_select -> ROM backend), must run on the emulator and reproduce
//! the host integer evaluator byte-exactly.
//!
//! This is the same gate machinery the real-checkpoint `compile-gate` bin
//! uses, on a synthetic checkpoint with a short generation to keep the
//! unoptimized-emulator cost bounded. The full 4-seed 256-token gate on the
//! committed export lives in `docs/experiments/gbf-compile` (program
//! generated by `cargo run -p gbf-bench --bin compile-gate`).

use gbf_bench::multi_token::run_seed_generation;
use gbf_codegen::compile::{CompileOptions, compile_checkpoint_export};
use gbf_codegen::import_checkpoint_export::write_synthetic_checkpoint_export;

#[test]
fn compiled_pipeline_rom_matches_host_generation_on_synthetic_export() {
    let dir = tempfile::tempdir().expect("tempdir");
    write_synthetic_checkpoint_export(dir.path(), 21).expect("writes export");
    let compiled = compile_checkpoint_export(dir.path(), &CompileOptions { n_tokens: 6 })
        .expect("compiles through the full pipeline");

    assert!(compiled.report.legalization.checks.iter().all(|c| c.ok));
    assert_eq!(compiled.report.rom.n_tokens, 6);

    for seed in [0x41u8, 0x0A] {
        let run = run_seed_generation(&compiled.rom, &compiled.int_model, seed).expect("gate runs");
        assert!(
            run.sequences_match,
            "seed 0x{seed:02X}: compiled ROM sequence diverged at {:?}",
            run.first_divergence_index
        );
        assert!(
            run.first_token_checkpoints_byte_exact && run.last_token_checkpoints_byte_exact,
            "seed 0x{seed:02X}: dump mismatches {:?}",
            run.checkpoint_mismatches
        );
        assert!(
            run.sp_home_every_token && run.wram_untouched_regions_ok && run.done_flag_set,
            "seed 0x{seed:02X}: health checks failed"
        );
        assert_eq!(run.rom_sequence.len(), 6);
    }
}
