#!/usr/bin/env python3
"""Materialize data.js from the committed acceptance evidence.

Everything shown as "real" in the film comes from here:
  - framebuffer.pgm   : exact 160x144 pixels of the accepted ROM session
  - acceptance-result : prompt/generated token IDs and per-token M-cycle timings
  - tokenizer (pinned SHA-256 ffae9160...) : decodes IDs to their byte strings

Run from anywhere:  python3 src/make_data.py
"""
import base64
import hashlib
import json
import os
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[3]
EVID = REPO / "docs/experiments/interactive-subword"
TOKENIZER_CANDIDATES = [
    pathlib.Path(os.environ["GBLLM_TOKENIZER"]) if os.environ.get("GBLLM_TOKENIZER") else None,
    REPO / "training/artifacts/tinystories_bpe_1024.json",
]
TOKENIZER_SHA = "ffae9160f720a680d18e2194ab86e44b23732ba0bcec68123cf04f49556443ad"

pgm = (EVID / "framebuffer.pgm").read_bytes()
header = b"P5\n160 144\n255\n"
assert pgm.startswith(header) and len(pgm) == len(header) + 160 * 144
pixels = pgm[len(header):]

acc = json.loads((EVID / "acceptance-result.json").read_text())
assert acc["passed"] is True

tok_path = next((p for p in TOKENIZER_CANDIDATES if p is not None and p.exists()), None)
if tok_path is None:
    raise SystemExit("Set GBLLM_TOKENIZER to the pinned tokenizer, or put it under training/artifacts/")
tok_bytes = tok_path.read_bytes()
assert hashlib.sha256(tok_bytes).hexdigest() == TOKENIZER_SHA, "tokenizer is not the pinned production tokenizer"
tok = json.loads(tok_bytes)
id_hex = tok["id_bytes_hex"]


def decode(i):
    h = id_hex[i] if isinstance(id_hex, list) else id_hex[str(i)]
    return bytes.fromhex(h).decode("latin1")


data = {
    "framebuffer": {
        "width": 160,
        "height": 144,
        "gray_b64": base64.b64encode(pixels).decode(),
        "sha256": hashlib.sha256(pgm).hexdigest(),
    },
    "prompt": acc["prompt"],
    "promptTokens": [[i, decode(i)] for i in acc["promptTokenIds"]],
    "generatedTokens": [[i, decode(i)] for i in acc["generatedIds"]],
    "generationBoundaryMCycles": acc["generationBoundaryMCycles"],
    "transcriptRows": acc["transcriptRows"],
}
assert "".join(s for _, s in data["generatedTokens"]).startswith(", there was a little girl named Lucy.")

out = HERE / "data.js"
out.write_text("// Generated by make_data.py from committed acceptance evidence. Do not edit.\n"
               "window.FILM_DATA = " + json.dumps(data) + ";\n")
print(out, "framebuffer sha256", data["framebuffer"]["sha256"])
