/// A fully assembled one-token ROM plus the facts the runner needs.
#[derive(Debug, Clone)]
pub struct OneTokenRom {
    pub rom: Vec<u8>,
    /// PC at which the measured token region begins (right after `di`/stack).
    pub token_start_pc: u16,
    /// PC of the spin loop reached when the token is complete.
    pub token_end_pc: u16,
    pub rom_size: RomSize,
    pub bank_count: u16,
    /// Bank-0 driver + routine + table bytes.
    pub driver_bytes: usize,
    /// Total straight-line weight-code bytes across all chunks.
    pub weight_code_bytes: usize,
    pub weight_chunk_count: usize,
    /// Banked data table bytes (embedding + head).
    pub table_bytes: usize,
}

/// A fully assembled multi-token generation ROM plus the facts the runner
/// needs. Same banked layout as [`OneTokenRom`]; the driver additionally
/// loops `n_tokens` times, writing each argmax byte to the [`OUT_BASE`] ring
/// and feeding it back as the next input.
#[derive(Debug, Clone)]
pub struct MultiTokenRom {
    pub rom: Vec<u8>,
    /// PC of the loop head (start of every token's forward pass).
    pub token_start_pc: u16,
    /// PC of the per-token boundary (the loop-back conditional jump), reached
    /// exactly once after each completed token with all dumps written and
    /// SP back at [`MODEL_STACK_TOP`].
    pub token_boundary_pc: u16,
    /// PC of the spin loop reached when all `n_tokens` are complete.
    pub token_end_pc: u16,
    /// Number of on-device generation steps (1..=256).
    pub n_tokens: u16,
    pub rom_size: RomSize,
    pub bank_count: u16,
    pub driver_bytes: usize,
    pub weight_code_bytes: usize,
    pub weight_chunk_count: usize,
    pub table_bytes: usize,
}

#[derive(Debug)]
pub enum ModelRomError {
    Encode(EncodeError),
    RomAssembly(RomAssemblyError),
    DuplicateLabel {
        name: String,
    },
    UndefinedLabel {
        name: String,
    },
    JrOutOfRange {
        label: String,
        offset: i32,
    },
    RowTooLargeForBank {
        row_bytes: usize,
    },
    DriverOverflowsBank0 {
        bytes: usize,
    },
    TooManyBanks {
        banks: usize,
    },
    BadTokenCount {
        n_tokens: u16,
    },
    UiBankOverflow {
        bytes: usize,
    },
    /// The topology's WRAM working set does not fit the 8 KiB arena even
    /// after dropping optional debug dumps and overlaying scratch buffers.
    WramOverflow {
        needed: usize,
        budget: usize,
        detail: String,
    },
    /// The per-row scale/decay parameter tables exceed one ROM bank.
    ParamsBankOverflow {
        bytes: usize,
    },
    /// A banked data table's padded row stride exceeds one ROM bank.
    TableRowTooWide {
        stride: usize,
    },
    /// V2 dispatch requires each matvec/segment column count to be a multiple
    /// of four (the base-81 packing groups four trits per byte).
    V2FanInNotMultipleOfFour {
        cols: usize,
    },
}

impl fmt::Display for ModelRomError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Encode(error) => write!(f, "{error}"),
            Self::RomAssembly(error) => write!(f, "{error}"),
            Self::DuplicateLabel { name } => write!(f, "duplicate label {name}"),
            Self::UndefinedLabel { name } => write!(f, "undefined label {name}"),
            Self::JrOutOfRange { label, offset } => {
                write!(f, "jr to {label} out of range ({offset})")
            }
            Self::RowTooLargeForBank { row_bytes } => {
                write!(
                    f,
                    "one matvec row needs {row_bytes} bytes, exceeding a bank"
                )
            }
            Self::DriverOverflowsBank0 { bytes } => {
                write!(f, "bank-0 driver needs {bytes} bytes past 0x0150..0x4000")
            }
            Self::TooManyBanks { banks } => write!(f, "model needs {banks} ROM banks (> 512)"),
            Self::BadTokenCount { n_tokens } => {
                write!(f, "n_tokens {n_tokens} outside the ring capacity 1..=256")
            }
            Self::UiBankOverflow { bytes } => {
                write!(
                    f,
                    "shell UI bank needs {bytes} bytes, exceeding one ROM bank"
                )
            }
            Self::WramOverflow {
                needed,
                budget,
                detail,
            } => {
                write!(
                    f,
                    "WRAM working set needs {needed} bytes of the {budget}-byte arena: {detail}"
                )
            }
            Self::ParamsBankOverflow { bytes } => {
                write!(
                    f,
                    "scale/decay parameter tables need {bytes} bytes (> one bank)"
                )
            }
            Self::TableRowTooWide { stride } => {
                write!(f, "banked table row stride {stride} exceeds one ROM bank")
            }
            Self::V2FanInNotMultipleOfFour { cols } => {
                write!(
                    f,
                    "v2 dispatch needs a column count multiple of 4 (got {cols})"
                )
            }
        }
    }
}

impl std::error::Error for ModelRomError {}

impl From<EncodeError> for ModelRomError {
    fn from(error: EncodeError) -> Self {
        Self::Encode(error)
    }
}

impl From<RomAssemblyError> for ModelRomError {
    fn from(error: RomAssemblyError) -> Self {
        Self::RomAssembly(error)
    }
}

// ---------------------------------------------------------------------------
// small two-pass assembler with call/label-immediate support
// ---------------------------------------------------------------------------

pub(crate) enum ModelOp {
    Instr(Instr),
    Label(String),
    Jp {
        cond: Option<Cond>,
        label: String,
    },
    Jr {
        cond: Option<Cond>,
        label: String,
    },
    CallLabel {
        label: String,
    },
    /// `ld rr, label + off`
    Ld16Label {
        dst: Reg16Data,
        label: String,
        off: i32,
    },
    Bytes(Vec<u8>),
    /// Two data bytes: the resolved little-endian address of `label`.
    WordLabel {
        label: String,
    },
}

pub(crate) struct ModelAsm {
    start: u16,
    ops: Vec<ModelOp>,
    unique: u32,
}

impl ModelAsm {
    pub(crate) fn new(start: u16) -> Self {
        Self {
            start,
            ops: Vec::new(),
            unique: 0,
        }
    }

    pub(crate) fn i(&mut self, instr: Instr) {
        self.ops.push(ModelOp::Instr(instr));
    }

    pub(crate) fn label(&mut self, name: &str) {
        self.ops.push(ModelOp::Label(name.to_owned()));
    }

    pub(crate) fn fresh(&mut self, prefix: &str) -> String {
        self.unique += 1;
        format!("{prefix}_{}", self.unique)
    }

    pub(crate) fn jp(&mut self, cond: Option<Cond>, label: &str) {
        self.ops.push(ModelOp::Jp {
            cond,
            label: label.to_owned(),
        });
    }

    pub(crate) fn jr(&mut self, cond: Option<Cond>, label: &str) {
        self.ops.push(ModelOp::Jr {
            cond,
            label: label.to_owned(),
        });
    }

    pub(crate) fn call(&mut self, label: &str) {
        self.ops.push(ModelOp::CallLabel {
            label: label.to_owned(),
        });
    }

    pub(crate) fn ld16_label(&mut self, dst: Reg16Data, label: &str, off: i32) {
        self.ops.push(ModelOp::Ld16Label {
            dst,
            label: label.to_owned(),
            off,
        });
    }

    pub(crate) fn bytes(&mut self, bytes: Vec<u8>) {
        self.ops.push(ModelOp::Bytes(bytes));
    }

    /// Emit the resolved little-endian address of `label` as two data bytes
    /// (used to build the V2 dispatch handler table).
    pub(crate) fn word_label(&mut self, label: &str) {
        self.ops.push(ModelOp::WordLabel {
            label: label.to_owned(),
        });
    }

    fn op_len(op: &ModelOp) -> u16 {
        match op {
            ModelOp::Instr(instr) => u16::from(instr.byte_len()),
            ModelOp::Jp { .. } | ModelOp::CallLabel { .. } | ModelOp::Ld16Label { .. } => 3,
            ModelOp::Jr { .. } => 2,
            ModelOp::Bytes(bytes) => bytes.len() as u16,
            ModelOp::WordLabel { .. } => 2,
            ModelOp::Label(_) => 0,
        }
    }

    pub(crate) fn finish(self) -> Result<(Vec<u8>, BTreeMap<String, u16>), ModelRomError> {
        let mut labels = BTreeMap::new();
        let mut pc = self.start;
        for op in &self.ops {
            if let ModelOp::Label(name) = op
                && labels.insert(name.clone(), pc).is_some()
            {
                return Err(ModelRomError::DuplicateLabel { name: name.clone() });
            }
            pc = pc.wrapping_add(Self::op_len(op));
        }

        let resolve = |label: &String| -> Result<u16, ModelRomError> {
            labels
                .get(label)
                .copied()
                .ok_or_else(|| ModelRomError::UndefinedLabel {
                    name: label.clone(),
                })
        };

        let mut bytes = Vec::new();
        let mut pc = self.start;
        for op in &self.ops {
            pc = pc.wrapping_add(Self::op_len(op));
            match op {
                ModelOp::Instr(instr) => bytes.extend_from_slice(&encode_instr(instr)?),
                ModelOp::Label(_) => {}
                ModelOp::Jp { cond, label } => {
                    let addr = resolve(label)?;
                    bytes.extend_from_slice(&encode_instr(&Instr::JpAbs { cond: *cond, addr })?);
                }
                ModelOp::CallLabel { label } => {
                    let addr = resolve(label)?;
                    bytes.extend_from_slice(&encode_instr(&Instr::Call { cond: None, addr })?);
                }
                ModelOp::Ld16Label { dst, label, off } => {
                    let addr = i32::from(resolve(label)?) + off;
                    let addr = u16::try_from(addr).map_err(|_| ModelRomError::JrOutOfRange {
                        label: label.clone(),
                        offset: *off,
                    })?;
                    bytes.extend_from_slice(&encode_instr(&Instr::Ld16Imm {
                        dst: *dst,
                        imm: addr,
                    })?);
                }
                ModelOp::Jr { cond, label } => {
                    let addr = resolve(label)?;
                    let offset = i32::from(addr) - i32::from(pc);
                    let offset = i8::try_from(offset).map_err(|_| ModelRomError::JrOutOfRange {
                        label: label.clone(),
                        offset,
                    })?;
                    bytes.extend_from_slice(&encode_instr(&Instr::JrRel {
                        cond: *cond,
                        off: offset,
                    })?);
                }
                ModelOp::Bytes(data) => bytes.extend_from_slice(data),
                ModelOp::WordLabel { label } => {
                    bytes.extend_from_slice(&resolve(label)?.to_le_bytes());
                }
            }
        }
        Ok((bytes, labels))
    }
}

