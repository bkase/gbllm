/// One matvec row as raw encoded bytes (no labels; purely straight-line).
/// `act_base` is the activation buffer the pop stream walks; the bias seed
/// is embedded mod 2^16 (exact whenever the true accumulator fits i16,
/// which the lowering's structural row bound guarantees for i16 layers).
fn encode_row(
    layer: &LoweredLayer,
    row: usize,
    act_base: u16,
    acc_out: u16,
) -> Result<Vec<u8>, ModelRomError> {
    let mut bytes = Vec::new();
    let mut push = |instr: Instr| -> Result<(), ModelRomError> {
        bytes.extend_from_slice(&encode_instr(&instr)?);
        Ok(())
    };
    push(Instr::Ld16Imm {
        dst: Reg16Data::DE,
        imm: (layer.biases[row] & 0xFFFF) as u16,
    })?;
    push(Instr::Ld16Imm {
        dst: Reg16Data::BC,
        imm: 0,
    })?;
    push(Instr::Ld16Imm {
        dst: Reg16Data::SP,
        imm: act_base,
    })?;

    encode_pop_accumulate(&mut push, layer.layer.row(row))?;

    // y = P - N -> ACC (i16 LE at a static address)
    push(Instr::Ld8Reg {
        dst: Reg8::A,
        src: Reg8::E,
    })?;
    push(Instr::SubA {
        src: AluSrc8::Reg(Reg8::C),
    })?;
    push(Instr::LdDirectFromA {
        addr: direct(acc_out),
    })?;
    push(Instr::Ld8Reg {
        dst: Reg8::A,
        src: Reg8::D,
    })?;
    push(Instr::SbcA {
        src: AluSrc8::Reg(Reg8::B),
    })?;
    push(Instr::LdDirectFromA {
        addr: direct(acc_out + 1),
    })?;
    Ok(bytes)
}

/// The V3 pop-stream accumulate body over one contiguous (even-length)
/// weight run: positives into DE, negatives into BC, zero pairs skipped via
/// `add sp`. The caller owns the DE/BC/SP seeds and the epilogue.
fn encode_pop_accumulate(
    push: &mut impl FnMut(Instr) -> Result<(), ModelRomError>,
    weights: &[i8],
) -> Result<(), ModelRomError> {
    debug_assert_eq!(weights.len() % 2, 0, "pop stream consumes column pairs");
    let mut pending_skip: u16 = 0;
    for pair in weights.chunks_exact(2) {
        if pair[0] == 0 && pair[1] == 0 {
            pending_skip += 2;
            continue;
        }
        while pending_skip > 0 {
            let chunk = pending_skip.min(126);
            if chunk == 2 {
                push(Instr::Pop {
                    dst: Reg16Stack::HL,
                })?;
            } else {
                push(Instr::AddSp { off: chunk as i8 })?;
            }
            pending_skip -= chunk;
        }
        push(Instr::Pop {
            dst: Reg16Stack::HL,
        })?;
        for (weight, reg) in [(pair[0], Reg8::L), (pair[1], Reg8::H)] {
            match weight {
                1 => {
                    push(Instr::Ld8Reg {
                        dst: Reg8::A,
                        src: reg,
                    })?;
                    // DE += A (branchless idiom from the bake-off)
                    push(Instr::AddA {
                        src: AluSrc8::Reg(Reg8::E),
                    })?;
                    push(Instr::Ld8Reg {
                        dst: Reg8::E,
                        src: Reg8::A,
                    })?;
                    push(Instr::AdcA {
                        src: AluSrc8::Reg(Reg8::D),
                    })?;
                    push(Instr::SubA {
                        src: AluSrc8::Reg(Reg8::E),
                    })?;
                    push(Instr::Ld8Reg {
                        dst: Reg8::D,
                        src: Reg8::A,
                    })?;
                }
                -1 => {
                    push(Instr::Ld8Reg {
                        dst: Reg8::A,
                        src: reg,
                    })?;
                    // BC += A; combined as P - N at row end
                    push(Instr::AddA {
                        src: AluSrc8::Reg(Reg8::C),
                    })?;
                    push(Instr::Ld8Reg {
                        dst: Reg8::C,
                        src: Reg8::A,
                    })?;
                    push(Instr::AdcA {
                        src: AluSrc8::Reg(Reg8::B),
                    })?;
                    push(Instr::SubA {
                        src: AluSrc8::Reg(Reg8::C),
                    })?;
                    push(Instr::Ld8Reg {
                        dst: Reg8::B,
                        src: Reg8::A,
                    })?;
                }
                _ => {}
            }
        }
    }
    Ok(())
}

/// Column-segment width for wide (i24) rows: any 192-column segment's
/// partial accumulator fits i16 structurally (worst case 128 * 192 =
/// 24,576), so each segment runs the proven V3 i16 stream and the segments
/// combine into a 3-byte accumulator with byte-serial adds.
pub(crate) const WIDE_SEGMENT_COLS: usize = 192;

/// One wide matvec row: column-segmented pop streams combined into a 3-byte
/// (i24) little-endian accumulator at `acc_out`. Exact mod-2^24 arithmetic;
/// the lowering's structural bound guarantees the true value fits i24.
fn encode_row_wide(
    layer: &TernaryLayer,
    row: usize,
    act_base: u16,
    acc_out: u16,
) -> Result<Vec<u8>, ModelRomError> {
    let mut bytes = Vec::new();
    let mut push = |instr: Instr| -> Result<(), ModelRomError> {
        bytes.extend_from_slice(&encode_instr(&instr)?);
        Ok(())
    };
    let weights = layer.row(row);
    debug_assert_eq!(weights.len() % 2, 0, "pop stream consumes column pairs");

    for (seg_idx, seg_start) in (0..weights.len()).step_by(WIDE_SEGMENT_COLS).enumerate() {
        let seg_end = (seg_start + WIDE_SEGMENT_COLS).min(weights.len());
        let seg = &weights[seg_start..seg_end];
        let seg_bias: i32 = seg.iter().map(|&w| -128 * i32::from(w)).sum();
        push(Instr::Ld16Imm {
            dst: Reg16Data::DE,
            imm: (seg_bias & 0xFFFF) as u16,
        })?;
        push(Instr::Ld16Imm {
            dst: Reg16Data::BC,
            imm: 0,
        })?;
        push(Instr::Ld16Imm {
            dst: Reg16Data::SP,
            imm: act_base + seg_start as u16,
        })?;
        encode_pop_accumulate(&mut push, seg)?;

        if seg_idx == 0 {
            // acc = sx24(P - N)
            push(Instr::Ld8Reg {
                dst: Reg8::A,
                src: Reg8::E,
            })?;
            push(Instr::SubA {
                src: AluSrc8::Reg(Reg8::C),
            })?;
            push(Instr::LdDirectFromA {
                addr: direct(acc_out),
            })?;
            push(Instr::Ld8Reg {
                dst: Reg8::A,
                src: Reg8::D,
            })?;
            push(Instr::SbcA {
                src: AluSrc8::Reg(Reg8::B),
            })?;
            push(Instr::LdDirectFromA {
                addr: direct(acc_out + 1),
            })?;
            // sign-extend the hi byte still in A: add a,a; sbc a,a
            push(Instr::AddA {
                src: AluSrc8::Reg(Reg8::A),
            })?;
            push(Instr::SbcA {
                src: AluSrc8::Reg(Reg8::A),
            })?;
            push(Instr::LdDirectFromA {
                addr: direct(acc_out + 2),
            })?;
        } else {
            // acc += sx24(P - N), byte-serial with carry
            push(Instr::Ld8Reg {
                dst: Reg8::A,
                src: Reg8::E,
            })?;
            push(Instr::SubA {
                src: AluSrc8::Reg(Reg8::C),
            })?;
            push(Instr::Ld8Reg {
                dst: Reg8::E,
                src: Reg8::A,
            })?;
            push(Instr::Ld8Reg {
                dst: Reg8::A,
                src: Reg8::D,
            })?;
            push(Instr::SbcA {
                src: AluSrc8::Reg(Reg8::B),
            })?;
            push(Instr::Ld8Reg {
                dst: Reg8::D,
                src: Reg8::A,
            })?;
            push(Instr::AddA {
                src: AluSrc8::Reg(Reg8::A),
            })?;
            push(Instr::SbcA {
                src: AluSrc8::Reg(Reg8::A),
            })?;
            push(Instr::Ld8Reg {
                dst: Reg8::B,
                src: Reg8::A,
            })?;
            push(Instr::LdAFromDirect {
                addr: direct(acc_out),
            })?;
            push(Instr::AddA {
                src: AluSrc8::Reg(Reg8::E),
            })?;
            push(Instr::LdDirectFromA {
                addr: direct(acc_out),
            })?;
            push(Instr::LdAFromDirect {
                addr: direct(acc_out + 1),
            })?;
            push(Instr::AdcA {
                src: AluSrc8::Reg(Reg8::D),
            })?;
            push(Instr::LdDirectFromA {
                addr: direct(acc_out + 1),
            })?;
            push(Instr::LdAFromDirect {
                addr: direct(acc_out + 2),
            })?;
            push(Instr::AdcA {
                src: AluSrc8::Reg(Reg8::B),
            })?;
            push(Instr::LdDirectFromA {
                addr: direct(acc_out + 2),
            })?;
        }
    }
    Ok(bytes)
}

fn chunk_prologue() -> Result<Vec<u8>, ModelRomError> {
    Ok(encode_instr(&Instr::LdDirectFromSp { addr: SPSAVE })?)
}

fn chunk_epilogue() -> Result<Vec<u8>, ModelRomError> {
    let mut bytes = Vec::new();
    for instr in [
        Instr::LdAFromDirect {
            addr: direct(SPSAVE),
        },
        Instr::Ld8Reg {
            dst: Reg8::L,
            src: Reg8::A,
        },
        Instr::LdAFromDirect {
            addr: direct(SPSAVE + 1),
        },
        Instr::Ld8Reg {
            dst: Reg8::H,
            src: Reg8::A,
        },
        Instr::LdSpFromHl,
        Instr::Ret { cond: None },
    ] {
        bytes.extend_from_slice(&encode_instr(&instr)?);
    }
    Ok(bytes)
}

/// Pack encoded rows into as few bank chunks as fit; each chunk is a
/// complete callable program at `CHUNK_ENTRY`.
fn pack_row_chunks(
    rows: impl Iterator<Item = Result<Vec<u8>, ModelRomError>>,
) -> Result<Vec<Vec<u8>>, ModelRomError> {
    let prologue = chunk_prologue()?;
    let epilogue = chunk_epilogue()?;
    let overhead = prologue.len() + epilogue.len();

    let mut chunks = Vec::new();
    let mut current: Vec<u8> = prologue.clone();
    for row_bytes in rows {
        let row_bytes = row_bytes?;
        if row_bytes.len() + overhead > BANK_BYTES {
            return Err(ModelRomError::RowTooLargeForBank {
                row_bytes: row_bytes.len(),
            });
        }
        if current.len() + row_bytes.len() + epilogue.len() > BANK_BYTES {
            current.extend_from_slice(&epilogue);
            chunks.push(std::mem::replace(&mut current, prologue.clone()));
        }
        current.extend_from_slice(&row_bytes);
    }
    current.extend_from_slice(&epilogue);
    chunks.push(current);
    Ok(chunks)
}

/// Pack one i16 matvec's rows into bank chunks: activations popped from
/// `act_base`, 2-byte accumulators written from `acc_base` up.
pub(crate) fn build_matvec_chunks_at(
    layer: &LoweredLayer,
    act_base: u16,
    acc_base: u16,
) -> Result<Vec<Vec<u8>>, ModelRomError> {
    pack_row_chunks(
        (0..layer.layer.rows())
            .map(|row| encode_row(layer, row, act_base, acc_base + 2 * row as u16)),
    )
}

/// Pack one wide (i24) matvec's rows into bank chunks: column-segmented
/// pop streams, 3-byte accumulators written from `acc_base` up.
pub(crate) fn build_matvec_chunks_wide(
    layer: &TernaryLayer,
    act_base: u16,
    acc_base: u16,
) -> Result<Vec<Vec<u8>>, ModelRomError> {
    pack_row_chunks(
        (0..layer.rows())
            .map(|row| encode_row_wide(layer, row, act_base, acc_base + 3 * row as u16)),
    )
}

/// Dense-convention chunks at the fixed v0 addresses ([`ACT_BASE`],
/// [`ACC_BASE`]).
pub(crate) fn build_matvec_chunks(layer: &LoweredLayer) -> Result<Vec<Vec<u8>>, ModelRomError> {
    build_matvec_chunks_at(layer, ACT_BASE, ACC_BASE)
}

// ---------------------------------------------------------------------------
// V2 dispatch stream codegen (weights-as-data, walked by a shared handler)
// ---------------------------------------------------------------------------
//
// The V2 lowering packs each matvec's weights into a base-81 dispatch stream
// (~0.25 B/weight vs V3's ~6.6 B/weight) that a shared bank-0 routine threads,
// reproducing the SAME integer accumulator V3 emits as straight-line code:
// `acc = (-128*sum(row)) + sum(+/- act_j)` mod 2^16 per row/segment. Only the
// per-matvec accumulation *emission* changes; every epilogue and the WRAM
// layout are untouched (design: docs/design/v2-dispatch-stateful.md).

/// V2 dispatch sentinel: end of a wide segment that continues the same row
/// (combine the i16 partial into the i24 row accumulator, keep threading).
pub(crate) const V2_SEG_MID: u8 = 83;
/// V2 dispatch sentinel: end of the last segment of a wide row that is not the
/// final row (combine, store the i24 accumulator, advance the output pointer).
pub(crate) const V2_ROW_END_WIDE: u8 = 84;
/// V2 dispatch sentinel: end of the last segment of the final wide row
/// (combine, store, return).
pub(crate) const V2_MATRIX_END_WIDE: u8 = 85;
/// Number of dispatch-table entries: 81 pattern handlers + i16 row/matrix end
/// + the three wide sentinels.
pub(crate) const V2_TABLE_LEN: usize = 86;

/// Pack one i16 matvec into a V2 dispatch stream:
/// `bias_0 (i16 LE) | row_0 base-81 bytes | ROW_END | ... | bias_last |
/// row_last | MATRIX_END`. The bias is `layer.biases[row]` mod 2^16 — exactly
/// the DE seed `encode_row` embeds — so the threaded accumulator matches the
/// V3 straight-line code bit-for-bit.
pub(crate) fn build_matvec_stream_i16(layer: &LoweredLayer) -> Result<Vec<u8>, ModelRomError> {
    let rows = layer.layer.rows();
    let cols = layer.layer.cols();
    if !cols.is_multiple_of(4) {
        return Err(ModelRomError::V2FanInNotMultipleOfFour { cols });
    }
    let mut stream = Vec::with_capacity(rows * (cols / 4 + 3));
    for row in 0..rows {
        let bias = (layer.biases[row] & 0xFFFF) as u16;
        stream.extend_from_slice(&bias.to_le_bytes());
        for chunk in layer.layer.row(row).chunks_exact(4) {
            stream.push(crate::spec::base81_index(chunk));
        }
        stream.push(if row + 1 == rows {
            crate::spec::BASE81_MATRIX_END
        } else {
            crate::spec::BASE81_ROW_END
        });
    }
    Ok(stream)
}

/// Pack one wide (i24) matvec into a V2 dispatch stream: each row is split into
/// [`WIDE_SEGMENT_COLS`]-column segments, each framed
/// `seg_bias (i16 LE) | seg base-81 bytes | SENTINEL`, where the sentinel is
/// `SEG_MID` (more segments in this row), `ROW_END_WIDE` (last segment of a
/// non-final row), or `MATRIX_END_WIDE` (last segment of the final row). The
/// per-segment bias is `-128 * sum(seg)`, matching `encode_row_wide`; the
/// threaded i16 partials sign-extend and combine into the i24 accumulator
/// exactly as the V3 wide code does.
pub(crate) fn build_matvec_stream_wide(layer: &TernaryLayer) -> Result<Vec<u8>, ModelRomError> {
    let rows = layer.rows();
    let cols = layer.cols();
    if !cols.is_multiple_of(4) {
        return Err(ModelRomError::V2FanInNotMultipleOfFour { cols });
    }
    let mut stream = Vec::new();
    for row in 0..rows {
        let weights = layer.row(row);
        let last_row = row + 1 == rows;
        let n_segments = weights.len().div_ceil(WIDE_SEGMENT_COLS);
        for (seg_idx, seg_start) in (0..weights.len()).step_by(WIDE_SEGMENT_COLS).enumerate() {
            let seg_end = (seg_start + WIDE_SEGMENT_COLS).min(weights.len());
            let seg = &weights[seg_start..seg_end];
            let seg_bias: i32 = seg.iter().map(|&w| -128 * i32::from(w)).sum();
            stream.extend_from_slice(&((seg_bias & 0xFFFF) as u16).to_le_bytes());
            for chunk in seg.chunks_exact(4) {
                stream.push(crate::spec::base81_index(chunk));
            }
            let last_seg = seg_idx + 1 == n_segments;
            stream.push(match (last_seg, last_row) {
                (false, _) => V2_SEG_MID,
                (true, false) => V2_ROW_END_WIDE,
                (true, true) => V2_MATRIX_END_WIDE,
            });
        }
    }
    Ok(stream)
}

